"""billing_guard — hard "subscription tokens only" enforcement for the W2 runner.

Threat model: Claude Code silently prefers ANTHROPIC_API_KEY over the
subscription login, and an apiKeyHelper in settings can inject one — either
turns a "free under my plan" run into a metered API bill. This module makes
that impossible to do silently:

  G1  REFUSE TO START if ANTHROPIC_API_KEY or ANTHROPIC_AUTH_TOKEN is set in
      the environment (and scrub both from every subprocess env regardless).
  G2  REFUSE TO START if any Claude Code settings file in scope defines an
      `apiKeyHelper` (a script that supplies an API key behind your back).
  G3  PREFLIGHT: run a 1-token `claude -p` probe under the scrubbed env; it
      must succeed (proves the subscription login works with no key present)
      and must not report a billable cost.
  G4  PER-CALL TRIPWIRE: every packet execution's JSON result is inspected;
      any nonzero `total_cost_usd` (API metering) aborts the runner AND the
      server independently rejects the result (main.py). Subscription-billed
      calls do not produce a billable dollar figure.
  G5  USAGE LEDGER: token usage per packet is reported to the server so the
      operator can watch plan-credit consumption per run.

Nothing here can *grant* access — it can only refuse unsafe configurations.
"""
from __future__ import annotations
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

# Forbidden: metered-API credentials. NOTE deliberately absent from this list:
# CLAUDE_CODE_OAUTH_TOKEN (sk-ant-oat01-...), generated by `claude setup-token`.
# That token authenticates against the operator's SUBSCRIPTION (Pro/Max/Team/
# Enterprise) - usage draws on plan limits, no API invoice - and is Anthropic's
# sanctioned path for headless/CI runs. It must never be scrubbed. It is also,
# per Anthropic's Feb-2026 credential-use policy, valid ONLY inside Claude Code
# and claude.ai - this runner shells `claude -p` (Claude Code itself), which is
# exactly the permitted surface.
FORBIDDEN_ENV = ("ANTHROPIC_API_KEY", "ANTHROPIC_AUTH_TOKEN")
SETTINGS_CANDIDATES = (
    Path.home() / ".claude" / "settings.json",
    Path.cwd() / ".claude" / "settings.json",
    Path.cwd() / ".claude" / "settings.local.json",
)


class BillingGuardError(RuntimeError):
    pass


def scrubbed_env() -> dict:
    env = dict(os.environ)
    for k in FORBIDDEN_ENV:
        env.pop(k, None)
    return env


def check_environment() -> None:
    present = [k for k in FORBIDDEN_ENV if os.environ.get(k)]
    if present:
        raise BillingGuardError(
            f"G1: {', '.join(present)} is set. Claude Code would bill the API with it "
            "instead of your subscription. Unset it (e.g. `unset ANTHROPIC_API_KEY`) "
            "and, per Anthropic's guidance, `claude logout && claude login` with your "
            "Pro/Max/Team plan credentials only.")


def check_settings() -> None:
    for p in SETTINGS_CANDIDATES:
        if not p.exists():
            continue
        try:
            d = json.loads(p.read_text())
        except Exception:
            continue
        if "apiKeyHelper" in d:
            raise BillingGuardError(
                f"G2: {p} defines apiKeyHelper — a hook that supplies an API key and "
                "switches billing off your subscription. Remove it before running.")
        env_block = d.get("env") or {}
        bad = [k for k in FORBIDDEN_ENV if k in env_block]
        if bad:
            raise BillingGuardError(
                f"G2: {p} injects {bad} via its env block. Remove it before running.")


def _find_claude() -> str:
    exe = shutil.which("claude")
    if not exe:
        raise BillingGuardError(
            "Claude Code CLI not found on PATH. Install it and log in with your "
            "subscription: https://claude.com/claude-code, then `claude login`.")
    return exe


def usage_from_result(payload: dict) -> dict:
    u = payload.get("usage") or {}
    return {
        "input_tokens": u.get("input_tokens"),
        "output_tokens": u.get("output_tokens"),
        "cache_read_input_tokens": u.get("cache_read_input_tokens"),
        "total_cost_usd": payload.get("total_cost_usd") or payload.get("cost_usd") or 0.0,
        "model": payload.get("model") or payload.get("modelUsage") and list(
            payload.get("modelUsage", {}).keys())[:1],
        "duration_ms": payload.get("duration_ms"),
    }


def assert_not_billed(payload: dict, where: str) -> None:
    cost = float(payload.get("total_cost_usd") or payload.get("cost_usd") or 0.0)
    if cost > 0:
        raise BillingGuardError(
            f"G4 BILLING TRIPWIRE at {where}: Claude Code reported a billable API cost "
            f"(${cost}). This means the call was NOT covered by your subscription — "
            "the runner has stopped. Check `claude login` (subscription only) and that "
            "no API key/credits are attached to this login.")


def preflight() -> dict:
    check_environment()
    check_settings()
    exe = _find_claude()
    r = subprocess.run(
        [exe, "-p", "Reply with exactly: OK", "--output-format", "json"],
        env=scrubbed_env(), capture_output=True, text=True, timeout=180)
    if r.returncode != 0:
        hint = ("Log in with your plan (`claude login`), or for headless machines "
                "run `claude setup-token` on a browser machine and export the "
                "printed CLAUDE_CODE_OAUTH_TOKEN here (subscription-billed, "
                "sanctioned for CI/scripts).")
        if not os.environ.get("CLAUDE_CODE_OAUTH_TOKEN"):
            hint = "No subscription credential found. " + hint
        raise BillingGuardError(
            "G3 preflight failed: `claude -p` did not run under the scrubbed "
            f"(key-free) environment. {hint} stderr: {r.stderr[-400:]}")
    try:
        payload = json.loads(r.stdout)
    except json.JSONDecodeError:
        payload = {"result": r.stdout}
    assert_not_billed(payload, "preflight")
    return {"claude": exe, "preflight_usage": usage_from_result(payload)}


if __name__ == "__main__":
    try:
        info = preflight()
        print(json.dumps({"billing_guard": "PASS", **info}, indent=2))
    except BillingGuardError as e:
        print(json.dumps({"billing_guard": "FAIL", "reason": str(e)}, indent=2))
        sys.exit(2)
